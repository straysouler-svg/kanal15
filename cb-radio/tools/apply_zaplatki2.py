def load(f):
    return {r["n"]: r for r in json.loads(f.read_text(encoding="utf-8"))}


def save(f, rows_by_n, suf):
    rows = [rows_by_n[n] for n in sorted(rows_by_n)]
    f.write_text(json.dumps(rows, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    md = [f"# Драфты общих ответов на экзамен-2{' (EU)' if suf == 'eu' else ''} (400) — Gemini через OpenRouter, 22.11",
          "",
          "С канон-правками Летописца и решениями Дмитрия 22.11 (кошку Совы убрали — термос; три бытовые строки "
          "оставлены; #145 только в RU, в EU вычищен). НЕ интегрировано, НЕ озвучено. Флаги: «мат» — на фильтре "
          "Дмитрия, «canon?» — личный вопрос актёру. Машинный вид: " + f.name, ""]
    for r in rows:
        fl = ("  [" + ", ".join(r["flags"]) + "]") if r["flags"] else ""
        md.append(f"{r['n']}. **В:** {r['q']}")
        md.append(f"   **А:** {r['a']}{fl}")
        md.append("")
    f.with_suffix(".md").write_text("\n".join(md), encoding="utf-8")
    return rows


def find(rows, pat, field="qa"):
    rx = re.compile(pat, re.I)
    hits = [n for n, r in rows.items()
            if rx.search(r["q"] + " " + r["a"] if field == "qa" else r[field])]
    return hits


def apply_text(rows, pat, new, note, field="qa", expect=1):
    hits = find(rows, pat, field)
    if len(hits) != expect:
        print(f"  !! ТЕКСТ '{note}': совпадений {len(hits)} (ожидалось {expect}): {hits} — пропуск")
        return 0
    for n in hits:
        rows[n]["a"] = new
        rows[n]["flags"] = [f for f in rows[n]["flags"] if f != "мат"]   # пересчитаем ниже
    print(f"  OK текст {hits} <- {note}")
    return len(hits)


def drop_flag(rows, pat, note, field="q"):
    hits = find(rows, pat, field)
    for n in hits:
        rows[n]["flags"] = [f for f in rows[n]["flags"] if f != "canon?"]
    print(f"  OK флаг canon? снят у {hits or '∅'} <- {note}")
    return len(hits)


