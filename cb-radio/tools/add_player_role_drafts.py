def main():
    d = json.loads(JSON.read_text(encoding="utf-8"))
    actors = d["actors"]
    reactions = d["reactions"]

    added, dups = 0, []
    for key, lines in BAD_DAYS.items():
        existing = " ".join(p if isinstance(p, str) else p["text"] for p in actors[key]["phrases"])
        for text, mood in lines:
            if text in existing:
                dups.append((key, text))
            actors[key]["phrases"].append({"text": text, "mood": mood})
            added += 1
    print(f"bad_days: добавлено {added}, совпадений с существующими: {len(dups)}")
    for k, t in dups:
        print(f"  ДУБЛЬ {k}: {t}")

    reactions["intent"]["hush"] = HUSH
    reactions["intent"]["hush_back"] = HUSH_BACK
    reactions["errand"] = {"_": "«передай» — поручения по канону (drafts_player_role 2.1/2.2)"}
    for a, b, ask, reply in ERRAND_PAIRS:
        reactions["errand"][f"ask__{a}__{b}"] = [{"actor": a, "text": ask}]
        reactions["errand"][f"reply__{a}__{b}"] = [{"actor": b, "text": reply}]
    reactions["errand"]["late"] = ERRAND_LATE
    reactions["care"] = {"_": "«ты как, не спишь?» — забота ночью (drafts_player_role 3.1)"}
    for kind in ("ask", "ok", "tired", "silence"):
        reactions["care"][kind] = [{"actor": a, "text": lines[kind]} for a, lines in CARE.items()]
    n = len(HUSH) + len(HUSH_BACK) + len(ERRAND_LATE) + len(ERRAND_PAIRS) * 2 + len(CARE) * 4
    print(f"reactions: hush {len(HUSH)}, hush_back {len(HUSH_BACK)}, errand {len(ERRAND_PAIRS)} пар + late {len(ERRAND_LATE)}, care {len(CARE)}x4; всего {n}")

    JSON.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding="utf-8")
    print("json записан")


if __name__ == "__main__":
    main()
