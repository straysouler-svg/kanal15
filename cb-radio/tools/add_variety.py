def main(apply):
    data = json.loads(MAIN.read_text(encoding="utf-8"))
    for k in list(ADD) + [s for v in CROSS.values() for s, _ in v] + list(CROSS):
        assert k in data["actors"], k
    total = preview(data)
    print("реплик:", total, "->", PREVIEW)
    if not apply:
        return
    shutil.copy2(MAIN, MAIN.with_name("level3_eleven.before_variety.json"))
    r = data["reactions"]
    for k, lines in ADD.items():
        for pool, t in lines:
            g, kind = pool.split("/")
            lst = r.setdefault(g, {}).setdefault(kind, [])
            if not any(x.get("actor") == k and x.get("text") == t for x in lst):
                lst.append({"actor": k, "text": t})
    lst = r["intent"].setdefault("handle", [])
    for k, lines in HANDLE.items():
        for t in lines:
            if not any(x.get("actor") == k and x.get("text") == t for x in lst):
                lst.append({"actor": k, "text": t})
    fixed = [0]

    def fix_text(t):
        for _, old, new in AGE_FIX:
            if old in t:
                fixed[0] += 1
                t = t.replace(old, new)
        return t

    ph = data["actors"]["mihalych"]["phrases"]
    for i, x in enumerate(ph):
        if isinstance(x, str):
            ph[i] = fix_text(x)
        elif isinstance(x, dict) and "text" in x:
            x["text"] = fix_text(x["text"])

    def walk(node):
        if isinstance(node, dict):
            if node.get("actor") == "mihalych" and isinstance(node.get("text"), str):
                node["text"] = fix_text(node["text"])
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)
    walk(r)
    walk(data.get("scenes", {}))
    print("возраст: исправлено реплик", fixed[0], "из", len(AGE_FIX))
    r.setdefault("cross", {"_comment": "Третий вклинивается после ответа водителя <ключ> (ступень 2 вариативности)."})
    for who, lines in CROSS.items():
        lst = r["cross"].setdefault(who, [])
        for sp, t in lines:
            if not any(x.get("actor") == sp and x.get("text") == t for x in lst):
                lst.append({"actor": sp, "text": t})
    MAIN.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print("записано в", MAIN)


