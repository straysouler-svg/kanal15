def main():
    sys.stdout.reconfigure(encoding="utf-8")
    apply = "--apply" in sys.argv
    tx = lambda p: p["text"] if isinstance(p, dict) else p  # noqa: E731
    md = ["# Новые водители — реплики (на проверку перед озвучкой)", "",
          "Пометки в [скобках] и (скобках) — игра голосом, вслух не произносятся.", ""]
    chars_eleven = 0
    for a in ACTORS:
        md += [f"## {NAMES[a]}", "", "**Свои реплики в эфир** (первая — приветствие, последняя — прощание)"]
        md += [f"- {tx(p)}" for p in PHRASES[a]]
        chars_eleven += sum(len(tx(p)) for p in PHRASES[a])
        md.append("")
        for g, kinds in R.items():
            if g == "greet_reply":
                continue
            for k, lines in kinds.items():
                mine = [t for who, t in lines if who == a]
                if mine:
                    md.append(f"**{LABELS.get(f'{g}/{k}', f'{g}/{k}')}**")
                    md += [f"- {t}" for t in mine]
                    md.append("")
                    chars_eleven += sum(len(t) for t in mine)
    md += ["## Приветствия между старыми и новыми", ""]
    for k, lines in R["greet_reply"].items():
        for who, t in lines:
            md.append(f"- {NAMES.get(who, who)} отвечает на приветствие {NAMES.get(k, k)}: {t}")
            if who in ACTORS or who in ("mihalych", "stas", "boroda"):
                chars_eleven += len(t)
    md += ["", "## Сценки", ""]
    for sid, lines in SCENES.items():
        md.append(f"**{sid}**")
        for ln in lines:
            md.append(f"- {NAMES.get(ln['actor'], ln['actor'])}: {ln['text']}")
            if ln["actor"] in ACTORS or ln["actor"] in ("mihalych", "stas", "boroda"):
                chars_eleven += len(ln["text"])
        md.append("")
    md.insert(3, f"Около {chars_eleven} символов ElevenLabs; реплики Петровны, Студента, Палыча и Кардана — gpt-audio (центы).\n")
    PREVIEW.write_text("\n".join(md), encoding="utf-8")
    print(f"ElevenLabs символов: {chars_eleven} -> {PREVIEW.name}")
    if not apply:
        return
    missing = [a for a, v in VOICES.items() if not v]
    if missing:
        raise SystemExit(f"не выбраны голоса: {missing}")
    data = json.loads(MAIN.read_text(encoding="utf-8"))
    for a, spec in ACTORS.items():
        assert a not in data["actors"], a
        act = dict(spec)
        act.update(greet=[1], signoff=[len(PHRASES[a])], voice=VOICES[a], voice_id=VOICE_IDS[a][VOICES[a]],
                   model="eleven_v3", stability=STABILITY[a], phrases=PHRASES[a])
        data["actors"][a] = act
    for g, kinds in R.items():
        for k, lines in kinds.items():
            lst = data["reactions"].setdefault(g, {}).setdefault(k, [])
            have = {(x["actor"], x["text"]) for x in lst}
            lst.extend({"actor": w, "text": t} for w, t in lines if (w, t) not in have)
    for sid, lines in SCENES.items():
        assert sid not in data["scenes"], sid
        data["scenes"][sid] = lines
    shutil.copy(MAIN, MAIN.with_name("level3_eleven.before_new3.json"))
    MAIN.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print("записано: 3 водителя, реакции, сценки")


if __name__ == "__main__":
    main()
