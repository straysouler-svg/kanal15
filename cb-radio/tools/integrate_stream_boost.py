def add_buh():
    d = json.loads(L3.read_text(encoding="utf-8"))
    buh = d["reactions"]["buh"]
    added = 0
    for pool, val in BUH.items():
        if isinstance(val, dict):
            node = buh.setdefault(pool, {})
            for sub, texts in val.items():
                lst = node.setdefault(sub, [])
                for t in texts:
                    if not any(e.get("text") == t for e in lst):
                        lst.append({"actor": "buh", "text": t})
                        added += 1
        else:
            lst = buh.setdefault(pool, [])
            for t in val:
                if not any(e.get("text") == t for e in lst):
                    lst.append({"actor": "buh", "text": t})
                    added += 1
    L3.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding="utf-8")
    return added


def add_banter():
    d = json.loads(PL.read_text(encoding="utf-8"))
    sb = d["reactions"]["stream_banter"]
    added = 0
    for actor, texts in BANTER.items():
        lst = sb.setdefault(actor, [])
        for t in texts:
            if not any(e.get("text") == t for e in lst):
                lst.append({"actor": actor, "text": t})
                added += 1
    PL.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding="utf-8")
    return added


if __name__ == "__main__":
    a = add_buh()
    b = add_banter()
    print(f"buh: +{a}, banter: +{b}, всего +{a + b}")
