def main(apply):
    data = json.loads(MAIN.read_text(encoding="utf-8"))
    intent = data["reactions"]["intent"]
    n = 0
    for kind, lines in T.items():
        for actor, text in lines.items():
            assert actor in data["actors"] and actor != "soroka", actor
            assert "Железяк" not in text, text
            print(f"{kind:9} {actor:10} {text}")
            n += 1
    print("реплик:", n, "символов:", sum(len(t) for ls in T.values() for t in ls.values()))
    if apply:
        if any(k in intent for k in T):
            raise SystemExit("эти темы уже есть в базе")
        # text insertion at the end of reactions.intent: the file is hand-formatted (one line per phrase),
        # json.dumps would reflow all of it
        raw = MAIN.read_bytes()
        e = b"\r\n" if b'      ]\r\n    },\r\n    "player": {' in raw else b"\n"     # the file's own line ends
        anchor = e + b'      ]' + e + b'    },' + e + b'    "player": {'
        assert raw.count(anchor) == 1
        block = b"".join(
            b',' + e + b'      "' + k.encode() + b'": [' + e + (b"," + e).join(
                b"        " + json.dumps({"actor": a, "text": t}, ensure_ascii=False).encode("utf-8")
                for a, t in lines.items()) + e + b"      ]"
            for k, lines in T.items())
        new = raw.replace(anchor, e + b"      ]" + block + e + b'    },' + e + b'    "player": {')
        json.loads(new.decode("utf-8"))                       # still valid
        shutil.copy2(MAIN, MAIN.with_suffix(".before_zhenya.json"))
        MAIN.write_bytes(new)
        print("записано:", MAIN)


if __name__ == "__main__":
    main("--apply" in sys.argv)
