"""Фрагмент cb_radio.log для диагностического отчёта (2026-11-19, промт stabilizaciya_2026-11-19).

Порядок строк в журнале (контракт, P1-9): append-only ХРОНОЛОГИЯ — новые записи
дописываются В КОНЕЦ файла (_flush_log в cb_radio.py). До P1-9 файл был newest-first
(свежие — первые строки); если читаешь старый архивный файл той эпохи — свежие там
ПЕРВЫЕ, этот модуль ориентируется только на текущий порядок.

Для отчёта берём ПОСЛЕДНИЕ REPORT_LINES строк — они и есть самые свежие — и НЕ
переворачиваем: порядок уже хронологический, отчёт читается от старых к новым.
(Было до P0-3: splitlines()[-4000:] на newest-first файле — в отчёт попадали
самые старые записи, свежие отбрасывались.) Чистый модуль без зависимостей рации —
покрыт тестами tools/test_report_log.py.
"""
import re

REPORT_LINES = 4000
_HIDE_RX = re.compile(r"«[^»]*»")


def pick_log_fragment(data, hide_speech=False):
    """-> bytes: до REPORT_LINES самых свежих строк журнала в хронологическом порядке.

    Файл — append-only: свежие записи — ПОСЛЕДНИЕ физические строки (см. docstring модуля).
    Возвращаемые строки идут от более старых к более новым; переворот не нужен.
    hide_speech: фразы игрока в строках «тангента: «…»» заменены на «(скрыто)» — радио не отправляет
    слова игрока без его явного согласия."""
    lines = data.decode("utf-8", "replace").splitlines()[-REPORT_LINES:]
    if hide_speech:
        lines = [_HIDE_RX.sub("«(скрыто)»", ln) if "тангента" in ln and "«" in ln else ln
                 for ln in lines]
    return "\n".join(lines).encode("utf-8")
