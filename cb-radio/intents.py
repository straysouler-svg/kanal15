def graf(text):
    """-> 'graf_voice' | 'graf_cmd' | 'graf_greet' | None (the dog is not mentioned)."""
    t = norm(text)
    if " граф" not in t:
        return None
    if any(w in t for w in GRAF_VOICE):
        return "graf_voice"
    if any(f" {w}" in t for w in GRAF_CMD):
        return "graf_cmd"
    if any(w in t for w in GRAF_GREET):
        return "graf_greet"
    return None


