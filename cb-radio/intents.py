def full_name_call(text):
    """Обращение по полному имени/имени-отчеству/фамилии -> actor или None.
    «Зинаида Петровна, как дела?», «Сомов, приём», «слушай, Олег Павлович». Фамилии/ИО — только
    в позиции обращения, поэтому «верю в людей» и «вера в том, что…» сюда не попадают."""
    words = norm(text).split()
    if len(words) < 2:
        return None
    for actor, variants in FULL_NAMES.items():
        for v in variants:
            n = len(v)
            if len(words) > n and tuple(words[:n]) == v:
                return actor
            if words[0] in _CALL_WORDS and len(words) > n and tuple(words[1:1 + n]) == v:
                return actor
    return None


def its_me_question(text):
    """«это ты?», «Стас, это ты?», «ты Янек?» (2026-11-12, user): подтверждение, что на связи именно он.
    Отвечает САМ адресат (пул its_me); без имени — тот, кто говорил последним."""
    t = norm(text)
    if any(w in t for w in (" это ты", " это вы", " ты ли это", " не ты ли", " это правда ты")):
        return True
    words = t.split()
    # «ты Янек?» — короткая фраза из «ты» + имени (имя режется из интентов, поэтому ловим отдельно)
    return bool(words and words[0] == "ты" and addressee(text) and len(words) <= 4)


def understand(text):
    if is_handle_question(text):
        return "handle", addressee(text)
    g = graf(text)
    if g:
        return g, "vera"
    who = addressee(text)
    nc = full_name_call(text)
    if nc:
        return "name_call", nc          # обращение по имени-отчеству/фамилии (1.34) — приоритет над who
    if who == "vera" and any(w in norm(text) for w in (" собак", " пес", " псин", " песик", " овчарк")):
        return "graf_greet", "vera"      # «Кинолог, как собака?» — Vera answers for Граф
    if its_me_question(text):
        return "its_me", addressee(text)
    i = intent(text)
    if i == "rude" and _INSULT_ABOUT.search(norm(text)) and not _RUDE_HARD.search(norm(text)):
        i = "how_are_you"
    return i, addressee(text)


