_RUDE_THOU = _re.compile(r"(^| )(ты|тебя|тебе|тобой)( |$)")
# 15.11 (ревью Клода, 2-й круг): обращение по имени — кому говорят, а не на кого ругаются
_INSULT_NOUN = r"(дурак|дура|дебил|идиот|козел|козлин|урод|тупой|тупая|тупица|мудак|чмо|лох|придурок|баран|осел|дубина|кретин)"
# «ну нахуй эту пробку» — брань с дополнением-предметом, не в адрес водителя
_SWEAR_OBJ = _re.compile(r"(нахуй|нахрен|нафиг|на фиг) (эту|этот|это|эти|его|ее|их|всю|весь|все|такую|такой|такое|эту хер)")
# «Иди ты! Серьёзно?» — удивление («не может быть»), не обида
_SURPRISE_MARK = _re.compile(r"(серьезно|да ладно|не может быть|неужели|правда что ли|да ну |да ну$)")


def _rude_directed(text, who):
    """Брань направлена В ВОДИТЕЛЯ? Полная обида — только тогда (ревью Клода 15.11).
    Длинный рассказ/анекдот (>8 слов) без «ты» — не оскорбление, даже если там «иди»/«вы».
    2-й круг: имя рядом с бранью само по себе НЕ направляет («Палыч, ну нахуй эту пробку» —
    жалоба Палычу на пробку). По имени — только грамматически: «Палыч, ты …», «Палыч — дурак»."""
    n = norm(text)
    if len(n.split()) > 8 and not _RUDE_THOU.search(n):
        return False
    # удивление: «Иди ты! Серьёзно?», «Да ладно!» — не обида
    if _SURPRISE_MARK.search(n) or ((" иди ты " in n or " идите вы " in n) and "?" in text):
        return False
    # брань на предмет: «ну нахрен эту пробку» (без «ты» — не в водителя)
    if _SWEAR_OBJ.search(n) and not _RUDE_THOU.search(n):
        return False
    if _RUDE_ADDR.search(n):
        return True
    # имя + существительное-оскорбление сразу после (или через «ты»): «Палыч, дурак», «Витёк, ты козёл»
    if who:
        for s in NAMES.get(who, []):
            st = s.replace("ё", "е").strip()
            if _re.search(r" " + st + r"[а-я]* (ты )?" + _INSULT_NOUN, n):
                return True
    return False


