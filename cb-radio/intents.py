def add_secrets(items):
    """Secret intents (tainik.py): [[kind, [stems]], ...] go first, so they win over everything else."""
    have = {n for n, _ in INTENTS}
    for kind, stems in reversed(items or []):
        if kind not in have:
            INTENTS.insert(0, (kind, list(stems)))
    global _INTENT_STEMS, _NAME_STEMS
    _INTENT_STEMS = {s2.replace("ё", "е") for _, st in INTENTS for s2 in st}
    _NAME_STEMS = tuple(sorted({s2.replace("ё", "е").strip() for st in NAMES.values() for s2 in st} - _INTENT_STEMS,
                               key=len, reverse=True))


def norm(text):
    t = text.lower().replace("ё", "е")
    t = re.sub(r"[^а-яa-z0-9 ]+", " ", t)
    return " " + re.sub(r"\s+", " ", t).strip() + " "


def addressee(text):
    t = norm(text)
    best = None
    for key, stems in NAMES.items():
        for s in stems:
            i = t.find(" " + s.replace("ё", "е").strip())
            if i >= 0 and (best is None or i < best[0]):
                best = (i, key)                     # the name said first wins
    return best[1] if best else None


_INTENT_STEMS = {s.replace("ё", "е") for _, stems in INTENTS for s in stems}
# name stems to mask before looking for the intent: «САМАРКАнд» hides «марка» (truck), so «Самарканд, как дела»
# was a truck question. Stems that are intent words themselves («мент» = police) stay.
_NAME_STEMS = tuple(sorted({s.replace("ё", "е").strip() for stems in NAMES.values() for s in stems} - _INTENT_STEMS,
                           key=len, reverse=True))


_NAME_STEMS_ALL = tuple(sorted({s.replace("ё", "е").strip() for stems in NAMES.values() for s in stems},
                               key=len, reverse=True))


def intent(text):
    t = " " + " ".join(w for w in norm(text).split() if not w.startswith(_NAME_STEMS)) + " "
    # «ты знаешь <X>?» / «а Сороку знаешь?»: слово «знаешь/знаете» + любое имя (имена режутся из t,
    # поэтому смотрим по исходному тексту). Без имени — не knows (не портим «ты знаешь, как дорога?»).
    if any(w in t for w in (" знаешь ", " знаете ")):
        if addressee(text) and len(norm(text).split()) <= 8:
            return "knows"
    for name, stems in INTENTS:
        if any(" " + s.replace("ё", "е") in t for s in stems):     # a stem starts a word (2026-11-05: «подожди»)
            return name
    return None


def intent_all(text):
    """Все интенты реплики в порядке, как сказаны (по позиции первого стема). 2026-11-11: «как дела,
    куда едешь, как погода?» -> ['how_are_you', 'where', 'weather'] — водитель отвечает на первый."""
    t = " " + " ".join(w for w in norm(text).split() if not w.startswith(_NAME_STEMS)) + " "
    hits = []
    for name, stems in INTENTS:
        pos = [i for i in (t.find(" " + s.replace("ё", "е")) for s in stems) if i >= 0]
        if pos:
            hits.append((min(pos), name))
    return [name for _, name in sorted(hits)]


